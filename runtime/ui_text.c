const char *ui_text_in(int language, const char *en) {
    if (language == LANGUAGE_ID_ENGLISH) return en;
    for (size_t i = 0; i < SDL_arraysize(texts); i++) {
        if (SDL_strcmp(texts[i].en, en)) continue;
        switch (language) {
        case LANGUAGE_ID_JAPANESE: return texts[i].ja;
        case LANGUAGE_ID_FRENCH: return texts[i].fr;
        case LANGUAGE_ID_GERMAN: return texts[i].de;
        case LANGUAGE_ID_ITALIAN: return texts[i].it;
        case LANGUAGE_ID_SPANISH: return texts[i].es;
        case LANGUAGE_ID_KOREAN: return texts[i].ko;
        case LANGUAGE_ID_CHINESE_S: return texts[i].zh_hans;
        case LANGUAGE_ID_CHINESE_T: return texts[i].zh_hant;
        default: return en;
        }
    }
    return en;
}

const char *ui_text(const char *en) { return ui_text_in(display_ui_language(), en); }

static const struct { const char *code, *name; int id; } languages[] = {
    {"en", "English", LANGUAGE_ID_ENGLISH}, {"fr", "Fran\xC3\xA7" "ais", LANGUAGE_ID_FRENCH},
    {"ja", "日本語", LANGUAGE_ID_JAPANESE}, {"de", "Deutsch", LANGUAGE_ID_GERMAN},
    {"it", "Italiano", LANGUAGE_ID_ITALIAN}, {"es", "Espa\xC3\xB1ol", LANGUAGE_ID_SPANISH},
    {"ko", "한국어", LANGUAGE_ID_KOREAN}, {"zh-Hans", "简体中文", LANGUAGE_ID_CHINESE_S},
    {"zh-Hant", "繁體中文", LANGUAGE_ID_CHINESE_T},
};

int ui_language_of(const char *code) {
    for (size_t i = 0; i < SDL_arraysize(languages); i++) if (!SDL_strcmp(code, languages[i].code)) return languages[i].id;
    return -1;
}

const char *ui_language_name(const char *code) {
    for (size_t i = 0; i < SDL_arraysize(languages); i++) if (!SDL_strcmp(code, languages[i].code)) return languages[i].name;
    return code;
}

int ui_game_language(void) {
    int l = ui_language_of(st_served());
    return l >= 0 ? l : rt_language();
}
