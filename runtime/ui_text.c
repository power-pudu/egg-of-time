const char *ui_text_in(int language, const char *en) {
    if (language == LANGUAGE_ID_ENGLISH) return en;
    for (size_t i = 0; i < SDL_arraysize(texts); i++) {
        if (!SDL_strcmp(texts[i].en, en)) return language == LANGUAGE_ID_FRENCH ? texts[i].fr : texts[i].ja;
    }
    return en;
}

const char *ui_text(const char *en) { return ui_text_in(display_language(), en); }
