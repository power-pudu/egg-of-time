"""Writes runtime/ui_font_ja.inc: the Japanese characters of runtime/ui_text.c as bitmaps, for the runtime's UI font.

Only the characters the menu uses are kept. The font itself is not in this repository (see LICENSE.md).
Usage: python tools/font/ui_font_ja.py <PixelMplus10-Regular.ttf>   (needs Pillow)
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROWS = 10
LANGUAGE_NAME = "日本語"  # the language setting's own label, in runtime/display.c


def main():
    font = ImageFont.truetype(sys.argv[1], ROWS)
    with open(os.path.join(ROOT, "runtime", "ui_text.c"), encoding="utf-8") as f:
        chars = sorted({c for c in f.read() + LANGUAGE_NAME if ord(c) >= 0x3000})
    with open(os.path.join(ROOT, "runtime", "ui_font_ja.inc"), "w", newline="\n", encoding="utf-8") as out:
        out.write("/* Generated by tools/font/ui_font_ja.py from PixelMplus10 (M+ license). Do not edit. */\n")
        out.write("/* U+code, width, then a row per line, bit 0 the leftmost pixel. */\n")
        for c in chars:
            width = round(font.getlength(c))
            im = Image.new("1", (16, ROWS + 4), 0)
            d = ImageDraw.Draw(im)
            d.fontmode = "1"
            d.text((0, 0), c, font=font, fill=1)
            box = im.getbbox()
            if box is None or box[3] > ROWS:
                sys.exit(f"{c}: not drawn within {ROWS} rows")
            rows = [sum(1 << x for x in range(16) if im.getpixel((x, y))) for y in range(ROWS)]
            out.write(f"{{0x{ord(c):04X}, {width}, {{" + ", ".join(f"0x{r:03X}" for r in rows) + f"}}}}, /* {c} */\n")
    print(len(chars), "characters")


if __name__ == "__main__":
    main()
