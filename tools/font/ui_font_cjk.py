"""Writes runtime/ui_font_cjk.inc: the Korean and Chinese characters of runtime/ui_text.c as bitmaps, for the runtime's
UI font, a table per language (Simplified and Traditional Chinese draw some characters differently).

Only the characters each language's menu text uses are kept, and its name in the Language setting (ui_text.c). The
font itself is not in this repository (see LICENSE.md).
Usage: python tools/font/ui_font_cjk.py <folder of Fusion Pixel Font 10px proportional .ttf files>   (needs Pillow)
"""
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ROWS = 10
TOP = 2  # the font's ideographs start 3 rows down: drawn from row 1, as ui_font_ja.inc's are
# ui_text.c's Text fields: en, fr, ja, de, it, es, ko, zh_hans, zh_hant
TABLES = [("ko", 6, "ko", "한국어"), ("zh_hans", 7, "zh_hans", "简体中文"), ("zh_hant", 8, "zh_hant", "繁體中文")]


def literal_fields(row):
    """The strings of one table row, adjacent literals joined."""
    fields, cur, any_lit, i = [], bytearray(), False, 0
    while i < len(row):
        ch = row[i]
        if ch == '"':
            i += 1
            while row[i] != '"':
                if row[i] == "\\":
                    if row[i + 1] == "x":
                        h = re.match(r"[0-9A-Fa-f]{1,2}", row[i + 2:]).group(0)
                        cur.append(int(h, 16))
                        i += 2 + len(h)
                        continue
                    cur += row[i + 1].encode()
                    i += 2
                    continue
                cur += row[i].encode()
                i += 1
            i += 1
            any_lit = True
        elif ch == ",":
            if any_lit:
                fields.append(cur.decode())
                cur, any_lit = bytearray(), False
            i += 1
        else:
            i += 1
    if any_lit:
        fields.append(cur.decode())
    return fields


def table_rows():
    """ui_text.c's table: each row's strings, in its fields' order."""
    with open(os.path.join(ROOT, "runtime", "ui_text.c"), encoding="utf-8") as f:
        text = f.read()
    body = text[text.index("static const Text texts[] = {"):]
    body = body[body.index("{") + 1:body.index("\n};")]
    return [literal_fields(r) for r in re.findall(r"\{(\"(?:[^{}])*?)\},", body, re.S)]


def main():
    rows = table_rows()
    with open(os.path.join(ROOT, "runtime", "ui_font_cjk.inc"), "w", newline="\n", encoding="utf-8") as out:
        out.write("/* Generated by tools/font/ui_font_cjk.py from Fusion Pixel Font 10px (SIL Open Font License). Do not edit. */\n")
        out.write("/* A table per language: U+code, width, then a row per line, bit 0 the leftmost pixel. */\n")
        for name, field, variant, label in TABLES:
            font = ImageFont.truetype(os.path.join(sys.argv[1], f"fusion-pixel-10px-proportional-{variant}.ttf"), ROWS)
            chars = sorted({c for r in rows if len(r) > field for c in r[field] + label if ord(c) >= 0x3000})
            out.write(f"#ifdef CJK_{name.upper()}\n")
            for c in chars:
                width = round(font.getlength(c))
                im = Image.new("1", (16, ROWS + 4), 0)
                d = ImageDraw.Draw(im)
                d.fontmode = "1"
                d.text((0, -TOP), c, font=font, fill=1)
                box = im.getbbox()
                if box is None or box[3] > ROWS:
                    sys.exit(f"{c}: not drawn within {ROWS} rows")
                bits = [sum(1 << x for x in range(16) if im.getpixel((x, y))) for y in range(ROWS)]
                out.write(f"{{0x{ord(c):04X}, {width}, {{" + ", ".join(f"0x{r:03X}" for r in bits) + f"}}}}, /* {c} */\n")
            out.write("#endif\n")
            print(name, len(chars), "characters")


if __name__ == "__main__":
    main()
